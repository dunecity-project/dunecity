#!/usr/bin/env python3
"""Formation duels: a round-robin of QuantBot attack-wave shapes (docs/formations.md, Formation research).

Every game is a Random Skirmish 1v1 generated by the real SkirmishGenerator: a mirrored
(point-symmetric) map, both starts with a Fortress base and a 20,000-credit army, two QuantBots
of the same difficulty. Each side's waves march in its own shape (the test-only
QuantBot::waveFormationOverride); the game ends when one house is eliminated or at the time
limit. Every pair of shapes plays on every map size and seed twice, the shapes swapping houses
(the match seed, map and start assignment stay the same), so house and start differences
cancel within a pair.

One probe binary is built first (run-campaign-balance.py), then the games run in parallel
processes. Each game appends one row to games.csv and its waves to waves.csv, and its run
directory is deleted straight away; games already in games.csv are skipped, so an interrupted
round-robin resumes. --report prints the markdown tables used in docs/formations.md.
"""
import argparse
import csv
import itertools
import random
import shutil
import statistics
import subprocess
import threading
import time
from collections import defaultdict
from concurrent.futures import ThreadPoolExecutor, as_completed
from pathlib import Path

root = Path(__file__).resolve().parents[2]
SHAPES = ('combined', 'box', 'line', 'column', 'wedge', 'vee', 'echelon', 'staggered', 'diamond', 'pincer')
SIZES = (64, 128, 192)
SEEDS = (7101, 7202, 7303)
# The two houses of a game, by the seed's position in --seeds (sonic tanks, devastators and
# deviators all appear).
HOUSE_PAIRS = (('atreides', 'harkonnen'), ('ordos', 'atreides'), ('harkonnen', 'ordos'))
KEY = ('tag', 'difficulty', 'size', 'seed', 'house_a', 'shape_a', 'house_b', 'shape_b')
HOUSE_FIELDS = ('alive', 'kill_value', 'loss_value', 'structures_destroyed', 'units_destroyed', 'structures',
                'army_value', 'army_units')
GAME_FIELDS = KEY + ('winner', 'end_s', 'waves', 'wall_s', 'map_skipped', 'error') + tuple(
    f'{field}_{side}' for side in ('a', 'b') for field in HOUSE_FIELDS)
WAVE_FIELDS = ('house', 'launched', 'members', 'engaged', 'arrived', 'lost', 'contact_s', 'engage_spread_s',
               'arrival_spread_s', 'shots30', 'loss60', 'kill60', 'survivors', 'lost_before_contact', 'formed',
               'formup_s', 'formation_end_s', 'in_formation_at_contact')
HOUSE_NUMBERS = {'harkonnen': '0', 'atreides': '1', 'ordos': '2'}
lock = threading.Lock()


def parse(line, marker):
    body = line.split(marker, 1)[1].strip()
    return dict(part.split('=', 1) for part in body.split() if '=' in part)


def read(path):
    if not path.exists():
        return []
    with path.open(newline='') as handle:
        return list(csv.DictReader(handle))


def append(path, fields, rows):
    with lock:
        new = not path.exists()
        with path.open('a', newline='') as handle:
            writer = csv.DictWriter(handle, fieldnames=fields)
            if new:
                writer.writeheader()
            writer.writerows(rows)


def schedule(args):
    """Every game of the round-robin, a whole seed at a time so partial results stay balanced."""
    games = []
    for index, seed in enumerate(args.seeds):
        house_a, house_b = HOUSE_PAIRS[index % len(HOUSE_PAIRS)]
        for size in args.sizes:
            for first, second in itertools.combinations(args.shapes, 2):
                for shape_a, shape_b in ((first, second), (second, first)):
                    games.append((args.tag, args.difficulty, str(size), str(seed), house_a, shape_a, house_b, shape_b))
    return games


def build_probe(args, scratch):
    probe = scratch / 'probe'
    binary = probe / 'balance-probe.app/Contents/MacOS/balance-probe'
    if binary.exists() and not args.rebuild:
        return binary
    shutil.rmtree(probe, ignore_errors=True)
    subprocess.run(['python3', str(root / 'tests/ai/run-campaign-balance.py'), '--build-dir', args.build_dir,
                    '--output-dir', str(probe), '--duel-map-size', '64', '--duel-map-seed', '1',
                    '--duel-sides', 'atreides:box,harkonnen:box', '--local-spectator', '--enemy-difficulty', 'hard',
                    '--partner-difficulty', 'hard', '--minutes', '1', '--capture-mib', '256'],
                   cwd=root, check=True, capture_output=True, text=True)
    shutil.rmtree(probe / 'profile', ignore_errors=True)
    return binary


def play(args, scratch, binary, key):
    tag, difficulty, size, seed, house_a, shape_a, house_b, shape_b = key
    out = scratch / '-'.join(key)
    shutil.rmtree(out, ignore_errors=True)
    command = ['python3', str(root / 'tests/ai/run-campaign-balance.py'), '--build-dir', args.build_dir,
               '--prebuilt-probe', str(binary), '--output-dir', str(out), '--duel-map-size', size,
               '--duel-map-seed', seed, '--duel-sides', f'{house_a}:{shape_a},{house_b}:{shape_b}',
               '--local-spectator', '--enemy-difficulty', difficulty, '--partner-difficulty', difficulty,
               '--minutes', str(args.minutes), '--seed', seed, '--capture-mib', '256',
               '--wall-timeout', str(args.wall_timeout)]
    started = time.time()
    outcome = subprocess.run(command, cwd=root, capture_output=True, text=True)
    wall = round(time.time() - started)
    log = out / 'run.log'
    lines = log.read_text(errors='replace').splitlines() if log.exists() else []
    houses = {parse(l, 'FORMATION_DUEL_HOUSE:')['house']: parse(l, 'FORMATION_DUEL_HOUSE:')
              for l in lines if 'FORMATION_DUEL_HOUSE:' in l}
    result = next((parse(l, 'FORMATION_DUEL_RESULT:') for l in lines if 'FORMATION_DUEL_RESULT:' in l), {})
    row = dict(zip(KEY, key))
    row.update(winner=result.get('winner', ''), end_s=result.get('end_s', ''), wall_s=wall,
               waves=sum('FORMATION_WAVE:' in l for l in lines),
               map_skipped=next((parse(l, 'FORMATION_DUEL_MAP:').get('skipped', '') for l in lines
                                 if 'FORMATION_DUEL_MAP:' in l), ''),
               error='' if outcome.returncode == 0 and result else f'rc={outcome.returncode}')
    for side, house in (('a', house_a), ('b', house_b)):
        data = houses.get(HOUSE_NUMBERS[house], {})
        for field in HOUSE_FIELDS:
            row[f'{field}_{side}'] = data.get(field, '')
    shape_of = {HOUSE_NUMBERS[house_a]: shape_a, HOUSE_NUMBERS[house_b]: shape_b}
    waves = []
    for l in lines:
        if 'FORMATION_WAVE:' not in l:
            continue
        wave = parse(l, 'FORMATION_WAVE:')
        waves.append({**dict(zip(KEY, key)), 'shape': shape_of.get(wave.get('house'), ''),
                      **{k: wave.get(k, '') for k in WAVE_FIELDS}})
    results = Path(args.results)
    if row['error']:
        (results / f'failed-{"-".join(key)}.txt').write_text(
            outcome.stdout[-4000:] + '\n' + outcome.stderr[-4000:] + '\n' + '\n'.join(lines[-60:]))
    else:
        append(results / 'waves.csv', KEY + ('shape',) + WAVE_FIELDS, waves)
        append(results / 'games.csv', GAME_FIELDS, [row])
    shutil.rmtree(out, ignore_errors=True)
    return row


def run(args):
    results = Path(args.results)
    results.mkdir(parents=True, exist_ok=True)
    scratch = Path(args.scratch)
    scratch.mkdir(parents=True, exist_ok=True)
    done = {tuple(r[k] for k in KEY) for r in read(results / 'games.csv')}
    todo = [key for key in schedule(args) if key not in done]
    print(f'{len(todo)} games to play ({len(done)} already in games.csv)', flush=True)
    if not todo:
        return
    binary = build_probe(args, scratch)
    started = time.time()
    with ThreadPoolExecutor(max_workers=args.jobs) as pool:
        futures = [pool.submit(play, args, scratch, binary, key) for key in todo]
        for count, future in enumerate(as_completed(futures), 1):
            row = future.result()
            winner = {HOUSE_NUMBERS[row['house_a']]: row['shape_a'], HOUSE_NUMBERS[row['house_b']]: row['shape_b']}.get(
                row['winner'], 'time-out')
            print(f'[{count}/{len(todo)} {round(time.time() - started)} s] {row["size"]}/{row["seed"]} '
                  f'{row["house_a"]}:{row["shape_a"]} v {row["house_b"]}:{row["shape_b"]} -> {winner} '
                  f'({row["end_s"]} s game, {row["wall_s"]} s wall){" " + row["error"] if row["error"] else ""}',
                  flush=True)


# ---- Report ---------------------------------------------------------------------------

def number(value, default=0.0):
    try:
        return float(value)
    except (TypeError, ValueError):
        return default


def sides(game):
    """(shape, opponent, score, own house fields, opponent fields) for both sides of a game."""
    winner = game['winner']
    result = []
    for me, them in (('a', 'b'), ('b', 'a')):
        house = HOUSE_NUMBERS[game[f'house_{me}']]
        score = 0.5 if winner in ('', '-1') else (1.0 if winner == house else 0.0)
        result.append((game[f'shape_{me}'], game[f'shape_{them}'], score,
                       {f: number(game[f'{f}_{me}']) for f in HOUSE_FIELDS},
                       {f: number(game[f'{f}_{them}']) for f in HOUSE_FIELDS}))
    return result


def bootstrap(scores, rounds=2000):
    """95% interval of the mean score, resampling games (fixed seed: the report is reproducible)."""
    if not scores:
        return (0.0, 0.0)
    rng = random.Random(20261015)
    means = sorted(statistics.mean(rng.choices(scores, k=len(scores))) for _ in range(rounds))
    return means[int(0.025 * rounds)], means[int(0.975 * rounds) - 1]


def report(args):
    results = Path(args.results)
    games = [g for g in read(results / 'games.csv') if g['tag'] == args.tag and g['difficulty'] == args.difficulty
             and g['shape_a'] in args.shapes and g['shape_b'] in args.shapes]
    waves = [w for w in read(results / 'waves.csv') if w['tag'] == args.tag and w['difficulty'] == args.difficulty
             and w['shape_a'] in args.shapes and w['shape_b'] in args.shapes]
    if not games:
        print('No games.')
        return
    per = defaultdict(list)
    for game in games:
        for shape, opponent, score, own, other in sides(game):
            per[shape].append((game, opponent, score, own, other))
    decided = sum(g['winner'] not in ('', '-1') for g in games)
    win_times = [number(g['end_s']) / 60 for g in games if g['winner'] not in ('', '-1')]
    print(f'{len(games)} games ({args.difficulty}, tag {args.tag}), {decided} decided '
          f'({100 * decided / len(games):.0f}%), median time to win {statistics.median(win_times) if win_times else 0:.1f} min, '
          f'time limit {args.minutes} min.\n')
    print('| Rank | Shape | Games | W-D-L | Score | 95% CI | By size ' + ' / '.join(str(s) for s in args.sizes)
          + ' | By seed (min-max) | Value margin / game | Enemy structures / game | Win time min |')
    print('|---|---|---|---|---|---|---|---|---|---|---|')
    table = []
    for shape, rows in per.items():
        scores = [r[2] for r in rows]
        mean = statistics.mean(scores)
        low, high = bootstrap(scores)
        by_size = []
        for size in args.sizes:
            s = [r[2] for r in rows if r[0]['size'] == str(size)]
            by_size.append(f'{statistics.mean(s):.2f}' if s else '-')
        by_seed = [statistics.mean([r[2] for r in rows if r[0]['seed'] == seed]) for seed in sorted({r[0]['seed'] for r in rows})]
        margin = statistics.mean(r[3]['kill_value'] - r[3]['loss_value'] for r in rows)
        structures = statistics.mean(r[3]['structures_destroyed'] for r in rows)
        wins = [number(r[0]['end_s']) / 60 for r in rows if r[2] == 1.0]
        w = sum(s == 1.0 for s in scores); d = sum(s == 0.5 for s in scores); l = sum(s == 0.0 for s in scores)
        table.append((mean, shape, len(rows), f'{w}-{d}-{l}', low, high, by_size, by_seed, margin, structures,
                      statistics.median(wins) if wins else 0))
    table.sort(key=lambda t: (-t[0], -t[8]))
    for rank, (mean, shape, n, wdl, low, high, by_size, by_seed, margin, structures, win_time) in enumerate(table, 1):
        print(f'| {rank} | {shape} | {n} | {wdl} | {mean:.3f} | {low:.2f}-{high:.2f} | {" / ".join(by_size)} | '
              f'{min(by_seed):.2f}-{max(by_seed):.2f} | {margin:+.0f} | {structures:.1f} | {win_time:.1f} |')

    order = [t[1] for t in table]
    print('\nHead to head (row shape\'s score against the column shape, both houses, all sizes and seeds):\n')
    print('| | ' + ' | '.join(order) + ' |')
    print('|---' * (len(order) + 1) + '|')
    for shape in order:
        cells = []
        for opponent in order:
            s = [r[2] for r in per[shape] if r[1] == opponent]
            cells.append('-' if shape == opponent or not s else f'{statistics.mean(s):.2f}')
        print(f'| {shape} | ' + ' | '.join(cells) + ' |')

    print('\nWaves (all waves of the shape, every game; first-minute trade from contact):\n')
    print('| Shape | Waves | Members / wave | Killed 60 s | Lost 60 s | Killed / lost | Survival | '
          'Arrival spread s | Contact s | In formation at contact |')
    print('|---|---|---|---|---|---|---|---|---|---|')
    for shape in order:
        mine = [w for w in waves if w['shape'] == shape]
        if not mine:
            continue
        members = sum(number(w['members']) for w in mine)
        kill = sum(number(w['kill60']) for w in mine)
        loss = sum(number(w['loss60']) for w in mine)
        survivors = sum(number(w['survivors']) for w in mine)
        contact = [number(w['contact_s']) for w in mine if number(w['contact_s'], -1) >= 0]
        spread = [number(w['arrival_spread_s']) for w in mine if number(w['arrived']) >= 2]
        formed = [number(w['in_formation_at_contact']) / max(1, number(w['members'])) for w in mine
                  if number(w['in_formation_at_contact'], -1) >= 0]
        print(f'| {shape} | {len(mine)} | {members / len(mine):.1f} | {kill / len(mine):.0f} | {loss / len(mine):.0f} | '
              f'{kill / max(1, loss):.2f} | {100 * survivors / max(1, members):.0f}% | '
              f'{statistics.mean(spread) if spread else 0:.1f} | {statistics.median(contact) if contact else 0:.1f} | '
              f'{100 * statistics.mean(formed) if formed else 0:.0f}% |')


parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
parser.add_argument('--build-dir', default=str(root / 'build'))
parser.add_argument('--results', required=True, help='Directory for games.csv and waves.csv')
parser.add_argument('--scratch', help='Directory for the probe binary and the (deleted) run directories')
parser.add_argument('--tag', default='round1', help='Label of the code variant being measured')
parser.add_argument('--difficulty', choices=('hard', 'brutal'), default='hard')
parser.add_argument('--minutes', type=int, default=40, help='Game minutes before a game is a time-out')
parser.add_argument('--wall-timeout', type=int, default=1800)
parser.add_argument('--sizes', nargs='+', type=int, default=list(SIZES))
parser.add_argument('--seeds', nargs='+', type=int, default=list(SEEDS))
parser.add_argument('--shapes', nargs='+', default=list(SHAPES))
parser.add_argument('--jobs', type=int, default=6, help='Games played in parallel')
parser.add_argument('--rebuild', action='store_true', help='Rebuild the probe binary even if one exists')
parser.add_argument('--report', action='store_true')
args = parser.parse_args()
if args.report:
    report(args)
else:
    if not args.scratch:
        parser.error('--scratch is required to play.')
    run(args)
