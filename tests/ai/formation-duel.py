def number(value, default=0.0):
    try:
        return float(value)
    except (TypeError, ValueError):
        return default


def sides(game, margin):
    """(shape, opponent, score, own house fields, opponent fields, strict score) for both sides of a game.

    The strict score counts eliminations only (1 win, 0 loss, 0.5 time-out). The score adjudicates
    a time-out on the unit trade: the side whose killed unit value exceeds the other's by at least
    'margin' credits wins it, otherwise it stays a draw."""
    winner = game['winner']
    result = []
    for me, them in (('a', 'b'), ('b', 'a')):
        house = HOUSE_NUMBERS[game[f'house_{me}']]
        own = {f: number(game.get(f'{f}_{me}')) for f in HOUSE_FIELDS}
        other = {f: number(game.get(f'{f}_{them}')) for f in HOUSE_FIELDS}
        strict = 0.5 if winner in ('', '-1') else (1.0 if winner == house else 0.0)
        score = strict
        if strict == 0.5:
            trade = own['kill_value'] - other['kill_value']
            score = 1.0 if trade >= margin else (0.0 if trade <= -margin else 0.5)
        result.append((game[f'shape_{me}'], game[f'shape_{them}'], score, own, other, strict))
    return result


def bootstrap(scores, rounds=2000):
    """95% interval of the mean score, resampling games (fixed seed: the report is reproducible)."""
    if not scores:
        return (0.0, 0.0)
    rng = random.Random(20261015)
    means = sorted(statistics.mean(rng.choices(scores, k=len(scores))) for _ in range(rounds))
    return means[int(0.025 * rounds)], means[int(0.975 * rounds) - 1]


def report(args):
    results = Path(args.results)
    # --tag may name several rounds for the report (round1,round2).
    tags, sizes, seeds = set(args.tag.split(',')), {str(s) for s in args.sizes}, {str(s) for s in args.seeds}
    def wanted(row):
        return (row['tag'] in tags and row['difficulty'] == args.difficulty and row['size'] in sizes
                and row['seed'] in seeds and row['shape_a'] in args.shapes and row['shape_b'] in args.shapes)
    games = [g for g in read(results / 'games.csv') if wanted(g)]
    waves = [w for w in read(results / 'waves.csv') if wanted(w)]
    if not games:
        print('No games.')
        return
    per = defaultdict(list)
    for game in games:
        for shape, opponent, score, own, other, strict in sides(game, args.adjudicate):
            per[shape].append((game, opponent, score, own, other, strict))
    decided = sum(g['winner'] not in ('', '-1') for g in games)
    win_times = [number(g['end_s']) / 60 for g in games if g['winner'] not in ('', '-1')]
    print(f'{len(games)} games ({args.difficulty}, tag {args.tag}), {decided} decided by elimination '
          f'({100 * decided / len(games):.0f}%), median time to win {statistics.median(win_times) if win_times else 0:.1f} min, '
          f'time limit {args.minutes} min; time-outs adjudicated on a unit trade of {args.adjudicate:.0f} credits or more.\n')
    print('| Rank | Shape | Games | Score | 95% CI | By size ' + ' / '.join(str(s) for s in args.sizes)
          + ' | By seed (min-max) | Eliminations W-D-L | Strict score | Value margin / game | Enemy structures / game | Win time min |')
    print('|---|---|---|---|---|---|---|---|---|---|---|---|')
    table = []
    for shape, rows in per.items():
        scores = [r[2] for r in rows]
        stricts = [r[5] for r in rows]
        mean = statistics.mean(scores)
        low, high = bootstrap(scores)
        by_size = []
        for size in args.sizes:
            s = [r[2] for r in rows if r[0]['size'] == str(size)]
            by_size.append(f'{statistics.mean(s):.2f}' if s else '-')
        by_seed = [statistics.mean([r[2] for r in rows if r[0]['seed'] == seed]) for seed in sorted({r[0]['seed'] for r in rows})]
        margin = statistics.mean(r[3]['kill_value'] - r[4]['kill_value'] for r in rows)
        structures = statistics.mean(r[3]['structures_destroyed'] for r in rows)
        wins = [number(r[0]['end_s']) / 60 for r in rows if r[5] == 1.0]
        w = sum(s == 1.0 for s in stricts); d = sum(s == 0.5 for s in stricts); l = sum(s == 0.0 for s in stricts)
        table.append((mean, shape, len(rows), f'{w}-{d}-{l}', low, high, by_size, by_seed, margin, structures,
                      statistics.median(wins) if wins else 0, statistics.mean(stricts)))
    table.sort(key=lambda t: (-t[0], -t[8]))
    for rank, (mean, shape, n, wdl, low, high, by_size, by_seed, margin, structures, win_time, strict) in enumerate(table, 1):
        print(f'| {rank} | {shape} | {n} | {mean:.3f} | {low:.2f}-{high:.2f} | {" / ".join(by_size)} | '
              f'{min(by_seed):.2f}-{max(by_seed):.2f} | {wdl} | {strict:.3f} | {margin:+.0f} | {structures:.1f} | {win_time:.1f} |')

    if 'none' in per:
        print('\nAgainst the control (None: no formation, the plain engine-Hunt waves), same maps, seeds and houses:\n')
        print('| Shape | Games v None | Score v None | 95% CI | Eliminations W-D-L | Strict score | Value margin / game | Verdict |')
        print('|---|---|---|---|---|---|---|---|')
        for t in table:
            shape = t[1]
            if shape == 'none':
                continue
            rows = [r for r in per[shape] if r[1] == 'none']
            if not rows:
                continue
            scores = [r[2] for r in rows]
            stricts = [r[5] for r in rows]
            low, high = bootstrap(scores)
            w = sum(s == 1.0 for s in stricts); d = sum(s == 0.5 for s in stricts); l = sum(s == 0.0 for s in stricts)
            verdict = 'beats None' if low > 0.5 else ('loses to None' if high < 0.5 else 'not distinguishable from None')
            print(f'| {shape} | {len(rows)} | {statistics.mean(scores):.3f} | {low:.2f}-{high:.2f} | {w}-{d}-{l} | '
                  f'{statistics.mean(stricts):.3f} | {statistics.mean(r[3]["kill_value"] - r[4]["kill_value"] for r in rows):+.0f} | {verdict} |')
        every = [r[2] for shape in per if shape != 'none' for r in per[shape] if r[1] == 'none']
        if every:
            low, high = bootstrap(every)
            print(f'| all shapes | {len(every)} | {statistics.mean(every):.3f} | {low:.2f}-{high:.2f} | | | | |')

    order = [t[1] for t in table]
    print('\nHead to head (row shape\'s score against the column shape, both houses, all sizes and seeds):\n')
    print('| | ' + ' | '.join(order) + ' |')
    print('|---' * (len(order) + 1) + '|')
    for shape in order:
        cells = []
        for opponent in order:
            s = [r[2] for r in per[shape] if r[1] == opponent]
            cells.append('-' if shape == opponent or not s else f'{statistics.mean(s):.2f}')
        print(f'| {shape} | ' + ' | '.join(cells) + ' |')

    print('\nWaves (all waves of the shape, every game; first-minute trade from contact):\n')
    print('| Shape | Waves | Members / wave | Killed 60 s | Lost 60 s | Killed / lost | Survival | '
          'Arrival spread s | Contact s | In formation at contact |')
    print('|---|---|---|---|---|---|---|---|---|---|')
    for shape in order:
        mine = [w for w in waves if w['shape'] == shape]
        if not mine:
            continue
        members = sum(number(w['members']) for w in mine)
        kill = sum(number(w['kill60']) for w in mine)
        loss = sum(number(w['loss60']) for w in mine)
        survivors = sum(number(w['survivors']) for w in mine)
        contact = [number(w['contact_s']) for w in mine if number(w['contact_s'], -1) >= 0]
        spread = [number(w['arrival_spread_s']) for w in mine if number(w['arrived']) >= 2]
        formed = [number(w['in_formation_at_contact']) / max(1, number(w['members'])) for w in mine
                  if number(w['in_formation_at_contact'], -1) >= 0]
        print(f'| {shape} | {len(mine)} | {members / len(mine):.1f} | {kill / len(mine):.0f} | {loss / len(mine):.0f} | '
              f'{kill / max(1, loss):.2f} | {100 * survivors / max(1, members):.0f}% | '
              f'{statistics.mean(spread) if spread else 0:.1f} | {statistics.median(contact) if contact else 0:.1f} | '
              f'{100 * statistics.mean(formed) if formed else 0:.0f}% |')


def export(args):
    """Writes the small CSVs kept in git: every game (games.csv as recorded) and the waves summed
    per round, size, seed and shape (waves-by-shape.csv; the raw waves.csv stays out of git)."""
    results, target = Path(args.results), Path(args.export)
    target.mkdir(parents=True, exist_ok=True)
    games = read(results / 'games.csv')
    with (target / 'games.csv').open('w', newline='') as handle:
        writer = csv.DictWriter(handle, fieldnames=GAME_FIELDS)
        writer.writeheader()
        writer.writerows(games)
    sums = defaultdict(lambda: defaultdict(float))
    for wave in read(results / 'waves.csv'):
        key = (wave['tag'], wave['difficulty'], wave['size'], wave['seed'], wave['shape'])
        s = sums[key]
        s['waves'] += 1
        for field in ('members', 'kill60', 'loss60', 'survivors', 'lost_before_contact', 'shots30'):
            s[field] += number(wave[field])
        if number(wave['contact_s'], -1) >= 0:
            s['contact_s'] += number(wave['contact_s'])
        if number(wave['arrived']) >= 2:
            s['spread_waves'] += 1
            s['arrival_spread_s'] += number(wave['arrival_spread_s'])
        if number(wave['in_formation_at_contact'], -1) >= 0:
            s['contact_waves'] += 1
            s['in_formation_at_contact'] += number(wave['in_formation_at_contact'])
        if number(wave.get('in_formation_10s'), -1) >= 0:
            s['waves_10s'] += 1
            s['in_formation_10s'] += number(wave['in_formation_10s'])
        if number(wave.get('together_at_contact'), -1) >= 0:
            s['met_waves'] += 1
            s['met_members'] += number(wave['members'])
            s['together_at_contact'] += number(wave['together_at_contact'])
            s['engaged10'] += number(wave.get('engaged10'))
    fields = ('tag', 'difficulty', 'size', 'seed', 'shape', 'waves', 'members', 'kill60', 'loss60', 'survivors',
              'lost_before_contact', 'shots30', 'spread_waves', 'arrival_spread_s', 'contact_waves', 'in_formation_at_contact',
              'waves_10s', 'in_formation_10s', 'met_waves', 'met_members', 'together_at_contact', 'engaged10', 'contact_s')
    with (target / 'waves-by-shape.csv').open('w', newline='') as handle:
        writer = csv.writer(handle)
        writer.writerow(fields)
        for key in sorted(sums):
            writer.writerow(list(key) + [f'{sums[key][f]:.1f}'.rstrip('0').rstrip('.') for f in fields[5:]])
    print(f'{len(games)} games and {len(sums)} wave sums written to {target}')


def pairing_report(args):
    """Per pairing (--pairs x:y), from x's side: the score, eliminations and game length; the
    waves of both sides (arrival spread, members together at contact and engaged within 10 s of
    it, formation at contact and 10 s later, first-minute trade, survival); and how often the
    hunt-party steps fired per game."""
    results = Path(args.results)
    tags, sizes, seeds = set(args.tag.split(',')), {str(s) for s in args.sizes}, {str(s) for s in args.seeds}
    def wanted(row):
        return (row['tag'] in tags and row['difficulty'] == args.difficulty and row['size'] in sizes
                and row['seed'] in seeds)
    games = [g for g in read(results / 'games.csv') if wanted(g)]
    waves = [w for w in read(results / 'waves.csv') if wanted(w)]
    print(f'{args.difficulty}, tag {args.tag}, sizes {" ".join(map(str, args.sizes))}; time-outs adjudicated on a unit '
          f'trade of {args.adjudicate:.0f} credits or more.\n')
    print('| Pairing | Games | Score | 95% CI | Eliminations W-L / time-outs | Strict score | Value margin / game | '
          'Median game min | Verdict |')
    print('|---|---|---|---|---|---|---|---|---|')
    wave_rows, party_rows, defence_rows, force_rows = [], [], [], []
    for x, y in pairs(args):
        mine = [g for g in games if {g['shape_a'], g['shape_b']} == {x, y}]
        rows = [s for g in mine for s in sides(g, args.adjudicate) if s[0] == x]
        if not rows:
            continue
        scores = [r[2] for r in rows]
        low, high = bootstrap(scores)
        w = sum(r[5] == 1.0 for r in rows); l = sum(r[5] == 0.0 for r in rows); d = sum(r[5] == 0.5 for r in rows)
        verdict = f'beats {y}' if low > 0.5 else (f'loses to {y}' if high < 0.5 else 'not distinguishable')
        print(f'| {x} v {y} | {len(rows)} | {statistics.mean(scores):.3f} | {low:.2f}-{high:.2f} | {w}-{l} / {d} | '
              f'{statistics.mean(r[5] for r in rows):.3f} | {statistics.mean(r[3]["kill_value"] - r[4]["kill_value"] for r in rows):+.0f} | '
              f'{statistics.median(number(g["end_s"]) / 60 for g in mine):.1f} | {verdict} |')
        keys = {tuple(g[k] for k in KEY) for g in mine}
        # Defence and pace, from x's side: structures lost (the opponent's kills), the home trade,
        # how long x's eliminations took, and the per-game force-candidate counters.
        wins = [number(g['end_s']) / 60 for g in mine for s in sides(g, args.adjudicate) if s[0] == x and s[5] == 1.0]
        home_kill = sum(r[3]['home_kill'] for r in rows); home_loss = sum(r[3]['home_loss'] for r in rows)
        defence_rows.append(f'| {x} v {y} | {statistics.mean(r[4]["structures_destroyed"] for r in rows):.1f} | '
                            f'{statistics.mean(r[3]["structures_destroyed"] for r in rows):.1f} | '
                            f'{home_loss / len(rows):.0f} | {home_kill / len(rows):.0f} | {home_kill / max(1, home_loss):.2f} | '
                            f'{statistics.median(wins) if wins else 0:.1f} | {len(wins)} |')
        if any(r[3][f] for r in rows for f in FORCE_FIELDS[2:]):
            force_rows.append(f'| {x} v {y} | ' + ' | '.join(f'{statistics.mean(r[3][f] for r in rows):.1f}'
                                                          for f in FORCE_FIELDS[2:]) + ' |')
        for shape in (x, y):
            sw = [wv for wv in waves if tuple(wv[k] for k in KEY) in keys and wv['shape'] == shape]
            members = sum(number(wv['members']) for wv in sw)
            kill = sum(number(wv['kill60']) for wv in sw); loss = sum(number(wv['loss60']) for wv in sw)
            met = [wv for wv in sw if number(wv['contact_s'], -1) >= 0]
            contact = [number(wv['contact_s']) for wv in met]
            spread = [number(wv['arrival_spread_s']) for wv in sw if number(wv['arrived']) >= 2]
            share = lambda ws, f: 100 * sum(number(wv.get(f)) for wv in ws) / max(1, sum(number(wv['members']) for wv in ws))
            formed = [wv for wv in sw if number(wv['in_formation_at_contact'], -1) >= 0]
            wave_rows.append(f'| {x} v {y} | {shape} | {len(sw)} | {members / max(1, len(sw)):.1f} | '
                             f'{statistics.median(contact) if contact else 0:.0f} | {statistics.mean(spread) if spread else 0:.0f} | '
                             f'{share([wv for wv in met if number(wv.get("together_at_contact"), -1) >= 0], "together_at_contact"):.0f}% | '
                             f'{share([wv for wv in met if number(wv.get("engaged10"), -1) >= 0], "engaged10"):.0f}% | '
                             f'{share(formed, "in_formation_at_contact"):.0f}% | '
                             f'{kill / max(1, len(sw)):.0f} | {loss / max(1, len(sw)):.0f} | {kill / max(1, loss):.2f} | '
                             f'{100 * sum(number(wv["survivors"]) for wv in sw) / max(1, members):.0f}% |')
            own = [s[3] for g in mine for s in sides(g, args.adjudicate) if s[0] == shape]
            if own and any(o['parties'] for o in own):
                per = lambda f: statistics.mean(o[f] for o in own)
                party_rows.append(f'| {x} v {y} | {shape} | ' + ' | '.join(f'{per(f):.1f}' for f in PARTY_FIELDS) + ' |')
    print('\nWaves of both sides (median contact time after launch; base-arrival spread; living members within 8 '
          'tiles of the main body at contact and members engaging within 10 s of contact, as a share of members; '
          'first-minute value killed and lost from contact; members alive 5 min after launch):\n')
    print('| Pairing | Side | Waves | Members / wave | Contact s | Arrival spread s | Together at contact | '
          'Engaged within 10 s | In formation at contact | Killed 60 s | Lost 60 s | Killed / lost | Survival |')
    print('|---|---|---|---|---|---|---|---|---|---|---|---|---|')
    print('\n'.join(wave_rows))
    if party_rows:
        print('\nHunt-party steps per game (QuantBot::blobStats):\n')
        print('| Pairing | Side | ' + ' | '.join(PARTY_FIELDS) + ' |')
        print('|---|---|' + '---|' * len(PARTY_FIELDS))
        print('\n'.join(party_rows))
    print('\nDefence and pace, first side of each pairing (per game: own structures lost and enemy structures '
          'destroyed; home trade = enemy value destroyed within 12 tiles of own buildings against own value lost '
          'there; median minutes to an elimination win):\n')
    print('| Pairing | Structures lost | Structures destroyed | Home loss | Home kill | Home kill / loss | Win min | Wins |')
    print('|---|---|---|---|---|---|---|---|')
    print('\n'.join(defence_rows))
    if force_rows:
        print('\nForce-candidate counters per game, first side (QuantBot::forceStats):\n')
        print('| Pairing | ' + ' | '.join(FORCE_FIELDS[2:]) + ' |')
        print('|---|' + '---|' * len(FORCE_FIELDS[2:]))
        print('\n'.join(force_rows))


