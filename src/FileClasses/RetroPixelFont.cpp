constexpr int glyphHeight = 12;

struct Glyph {
    int width = 0;
    std::array<std::uint16_t, glyphHeight> rows {};
};

// The slash-separated source masks are original artwork. Their two-cell stems
// survive the ordinary 14-22px menu sizes; counters and stepped arches are part
// of the masks, never generated by thresholding/downsampling a vector font.
constexpr Glyph glyph(std::string_view pattern) {
    Glyph result;
    int row = 0;
    int column = 0;
    for(char cell : pattern) {
        if(cell == '/') {
            if(column == 0 || row >= glyphHeight - 1
                || (result.width != 0 && result.width != column)) return {};
            result.width = std::max(result.width, column);
            column = 0;
            ++row;
        } else {
            if(column >= 16 || (cell != '#' && cell != '.')) return {};
            if(cell == '#') {
                result.rows[row] |= static_cast<std::uint16_t>(1u << column);
            }
            ++column;
        }
    }
    if(row != glyphHeight - 1 || column != result.width) return {};
    result.width = std::max(result.width, column);
    return result;
}

